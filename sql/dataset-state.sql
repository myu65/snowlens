-- Run after setup.sql, using a separate, narrow DATASET_STORAGE_OWNER role.
-- That role needs DML only on DATASETS and USAGE on CURRENT_PRINCIPAL.
-- It must not inherit private-store DML, business data SELECT or publication DDL.
CREATE OR REPLACE PROCEDURE SNOWFLAKE_APPS.APP.WRITE_DATASET(ITEM_ID VARCHAR, BODY VARCHAR)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  actor VARCHAR DEFAULT SNOWFLAKE_APPS.APP.CURRENT_PRINCIPAL();
  document VARIANT;
  affected NUMBER;
  invalid_input EXCEPTION (-20003, 'Invalid Dataset definition');
  denied EXCEPTION (-20004, 'Dataset ownership conflict');
BEGIN
  IF (actor IS NULL OR ITEM_ID IS NULL OR LENGTH(ITEM_ID) NOT BETWEEN 1 AND 80
      OR BODY IS NULL OR OCTET_LENGTH(BODY)>1000000) THEN RAISE invalid_input; END IF;
  document := PARSE_JSON(BODY);
  IF (COALESCE(NOT IS_OBJECT(document) OR document:id::VARCHAR <> ITEM_ID
      OR NOT IS_ARRAY(document:fields) OR NOT IS_OBJECT(document:defaultView)
      OR NOT IS_OBJECT(document:drill),TRUE)
      OR document:defaultView:join IS NOT NULL) THEN RAISE invalid_input; END IF;
  BEGIN TRANSACTION;
  MERGE INTO SNOWFLAKE_APPS.APP.DATASETS t
    USING (SELECT :actor OWNER, :ITEM_ID ID, :document PAYLOAD) s ON t.ID=s.ID
    WHEN MATCHED AND t.OWNER=s.OWNER THEN UPDATE SET PAYLOAD=s.PAYLOAD,UPDATED_AT=CURRENT_TIMESTAMP()
    WHEN NOT MATCHED THEN INSERT (OWNER,KIND,ID,PAYLOAD,UPDATED_AT)
      VALUES (s.OWNER,'dataset',s.ID,s.PAYLOAD,CURRENT_TIMESTAMP());
  affected := SQLROWCOUNT;
  IF (affected<>1) THEN RAISE denied; END IF;
  COMMIT;
  RETURN OBJECT_CONSTRUCT('id', ITEM_ID);
EXCEPTION
  WHEN OTHER THEN ROLLBACK; RAISE;
END;
$$;
-- GRANT USAGE ON DATABASE SNOWFLAKE_APPS TO ROLE <DATASET_STORAGE_OWNER_ROLE>;
-- GRANT USAGE ON SCHEMA SNOWFLAKE_APPS.APP TO ROLE <DATASET_STORAGE_OWNER_ROLE>;
-- GRANT USAGE ON FUNCTION SNOWFLAKE_APPS.APP.CURRENT_PRINCIPAL() TO ROLE <DATASET_STORAGE_OWNER_ROLE>;
-- GRANT SELECT, INSERT, UPDATE ON TABLE SNOWFLAKE_APPS.APP.DATASETS TO ROLE <DATASET_STORAGE_OWNER_ROLE>;
-- GRANT OWNERSHIP ON PROCEDURE SNOWFLAKE_APPS.APP.WRITE_DATASET(VARCHAR, VARCHAR)
--   TO ROLE <DATASET_STORAGE_OWNER_ROLE> COPY CURRENT GRANTS;
-- GRANT USAGE ON PROCEDURE SNOWFLAKE_APPS.APP.WRITE_DATASET(VARCHAR, VARCHAR) TO ROLE <DATASET_EDITOR_ROLE>;
-- GRANT CALLER USAGE ON PROCEDURE SNOWFLAKE_APPS.APP.WRITE_DATASET(VARCHAR, VARCHAR) TO ROLE <SERVICE_OWNER_ROLE>;
